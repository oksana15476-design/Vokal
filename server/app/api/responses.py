"""Описание ошибок в схеме OpenAPI.

Коды ошибок — часть контракта, а не деталь реализации: по ним фронтенд
ветвится. Поэтому каждый адрес перечисляет свои коды явно, а тела у всех
одинаковые — конверт из `app/core/errors.py`.
"""

from __future__ import annotations

from typing import Any

from app.api.schemas.common import ErrorEnvelope

DESCRIPTION_BY_STATUS: dict[int, str] = {
    400: "Запрос составлен неверно.",
    401: "Нужен вход в аккаунт.",
    403: "Доступ к этому объекту закрыт.",
    404: "Объект не найден или уже удален.",
    409: "Состояние объекта изменилось: обновите данные и повторите.",
    410: "Объект удален без возможности восстановления.",
    413: "Тело запроса больше допустимого.",
    415: "Формат содержимого не поддерживается.",
    422: "Данные запроса не прошли проверку схемы.",
    429: "Слишком много запросов подряд.",
    # 501 не «когда-нибудь сделаем»: адрес объявлен, схема настоящая,
    # реализации нет. Подробности отказа лежат в details.missing.
    501: "Адрес объявлен, реализации еще нет. В details.missing сказано, чего не хватает.",
    503: "Сервис временно недоступен.",
}


def errors(*statuses: int) -> dict[int | str, dict[str, Any]]:
    """Собирает блок `responses` для роутера."""
    return {
        status: {
            "model": ErrorEnvelope,
            "description": DESCRIPTION_BY_STATUS[status],
        }
        for status in statuses
    }


#: Набор для адреса, работающего с чужим объектом: не свой, не нашелся, нет реализации.
PROJECT_ERRORS = (401, 403, 404, 422, 501)
