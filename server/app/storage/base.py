"""Хранилище файлов.

Развилка «аудио через API или мимо него по подписанной ссылке» закрыта
решением от 2026-09-10: пока **через API**.

Основание. Подписанная ссылка требует выбранного провайдера объектного
хранения, а он не выбран. Строить presign против несуществующего провайдера —
та же ложная заглушка, которую мы выпалываем из интерфейса: снаружи выглядит
работающим, внутри пусто. Интерфейс ниже уже допускает оба режима, поэтому
переход на presign будет заменой реализации, а не переделкой вызывающего кода.

Следствия, принятые осознанно:
- лимит тела запроса остаётся десятками мегабайт и упирается в память и
  таймауты приложения;
- один поток загрузки на процесс приложения, а не мимо него.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass


@dataclass(frozen=True)
class StoredObject:
    """Что известно о положенном файле."""

    key: str
    size_bytes: int
    checksum_sha256: str
    content_type: str


class ObjectStorage(ABC):
    """Контракт хранилища. Реализации: локальный диск, S3-совместимое."""

    @abstractmethod
    async def put(self, key: str, data: bytes, content_type: str) -> StoredObject:
        """Кладёт объект. Перезапись существующего ключа — ошибка вызывающего."""

    @abstractmethod
    async def get(self, key: str) -> bytes:
        """Читает объект целиком. Для крупных файлов появится потоковый вариант."""

    @abstractmethod
    async def delete(self, key: str) -> bool:
        """Удаляет объект. `False` — объекта не было; это не ошибка."""

    @abstractmethod
    async def exists(self, key: str) -> bool: ...

    @abstractmethod
    async def signed_url(self, key: str, expires_seconds: int) -> str | None:
        """Ссылка на скачивание мимо приложения.

        `None` означает, что реализация так не умеет и файл придётся отдавать
        через API. Врать сгенерированным адресом, который никуда не ведёт,
        нельзя: снаружи он неотличим от рабочего.
        """
