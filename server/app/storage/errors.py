"""Отказы хранилища.

Отдельные классы, а не один `StorageError` с текстом, потому что вызывающий
код по-разному отвечает на разные отказы: отсутствие объекта — это 404,
несовпадение суммы — 500 и запись в аудит, неверная конфигурация — отказ
процесса подняться. Разбирать эти случаи по подстроке в сообщении — способ
однажды перепутать «файла нет» с «файл испорчен».

`InvalidKeyError` наследует и `ValueError`: это ошибка аргумента, и код,
который ловит `ValueError` на границе, не должен пропустить ее мимо.
"""

from __future__ import annotations


class StorageError(RuntimeError):
    """Общий предок отказов хранилища."""


class InvalidKeyError(StorageError, ValueError):
    """Ключ не проходит проверку: форма, запрещенные символы или выход за корень."""


class ObjectNotFoundError(StorageError):
    """Объекта по ключу нет."""


class ObjectAlreadyExistsError(StorageError):
    """Ключ занят. Перезапись запрещена: прежний файл уже мог быть отдан."""


class ChecksumMismatchError(StorageError):
    """Сумма прочитанного не совпала с записанной при укладке.

    Отдельный класс нужен именно затем, чтобы такой случай нельзя было
    случайно проглотить вместе с «файла нет»: испорченный файл, отданный как
    исправный, — худший исход из возможных.
    """


class StorageConfigurationError(StorageError):
    """Хранилище настроено неверно или не настроено вовсе."""
