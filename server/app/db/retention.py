"""Сроки хранения и физическое удаление объектов.

Модуль намеренно почти пустой, и это его содержание.

`docs/DELETION_AND_RETENTION_DESIGN.md`, раздел «Сроки хранения по умолчанию»:
величины «заполняются после ответов юриста». Значит, их сейчас нет. Поставить
здесь «90 дней» и разойтись — значит завести срок, которого никто не решал, и
дальше он молча превратится в обещание в политике хранения.

Физического удаления объектов тоже нет: объектного хранилища в проекте пока
нет вовсе. Функция, которая делает вид, что удалила файл, страшнее отсутствия
функции: удаление, о котором отчитались, но которого не было, — это ровно то
ложное обещание, ради предотвращения которого написан дизайн-док.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import datetime
from typing import NoReturn

#: Срок хранения по умолчанию. `None` — величина не определена, а не «бессрочно».
#: Заполняется решением владельца после ответов на вопросы 16-19
#: `docs/LEGAL_BRIEF.md`, вместе с разделом «Сроки хранения по умолчанию».
DEFAULT_RETENTION: None = None


def resolve_retention_until(deleted_at: datetime) -> datetime | None:
    """Момент, после которого удаленную строку можно снести физически.

    Пока политика хранения не заполнена, возвращает `None`: сметать по
    выдуманному сроку — потерять оплаченный результат раньше, чем разрешено,
    либо хранить дольше, чем обещано. Оба исхода хуже пустого поля.
    """
    if DEFAULT_RETENTION is None:
        return None
    raise NotImplementedError(
        "DEFAULT_RETENTION задан, но правило вычисления срока не написано."
    )


def purge_objects(storage_keys: Sequence[str]) -> NoReturn:
    """Физическое удаление объектов из хранилища. Не реализовано.

    Вызывать можно: падение с понятной причиной — это и есть честный ответ.
    Реализация появляется вместе с объектным хранилищем и обязана закрыть
    требования дизайн-дока: выключенное версионирование объектов, удаление
    неактуальных версий, чистку кэша CDN, отзыв выданных ссылок и
    подтвержденный статус вместо флага.
    """
    raise NotImplementedError(
        "Физическое удаление объектов не реализовано: объектного хранилища еще "
        f"нет. Запрошено ключей: {len(storage_keys)}. "
        "Пока не появится хранилище, статус удаления не может быть 'purged'."
    )
