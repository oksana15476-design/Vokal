"""Сроки хранения строк базы и физическое удаление объектов.

**Величины здесь не объявляются.** Они берутся из `app/storage/retention.py` —
единственного места, где сроки хранения решены. Раньше этот модуль объявлял
свой `DEFAULT_RETENTION = None` и писал, что величины «заполняются после
ответов юриста»; в `app/storage/retention.py` в это же время лежали 30/180/365
дней и пометка, что юридический трек закрыт решением владельца от 2026-09-10.
Два источника сроков хранения расходятся молча, и расходится всегда тот,
который показывают пользователю. Поэтому источник оставлен один, а этот модуль
только применяет его к строкам базы.

Разница между двумя сроками, чтобы ее не пришлось выводить заново:

- `app/storage/retention.py` отвечает на вопрос «докуда хранить **объект**»;
- этот модуль — «докуда хранить **строку**, которая на объект ссылается».

Строка обязана пережить объект. Если строку снести раньше, ключ объекта
исчезнет вместе с ней, и удалять в хранилище станет нечего и некому: файл
останется лежать, а обещание удаления превратится в ложное. Отсюда род
хранения по умолчанию — `results` (самый долгий из предметных): строка держится
столько же, сколько самый живучий объект, на который она может ссылаться.
Вызывающий, который точно знает род (например, строка загрузки ссылается
только на исходник), называет его сам.

Физического удаления объектов здесь по-прежнему нет, и функция об этом
говорит. Хранилище в проекте уже появилось (`app/storage/`), но одного
`delete()` для обещания «удалено» мало: дизайн-док требует выключенного
версионирования, чистки неактуальных версий, сброса кэша CDN, отзыва выданных
ссылок и подтвержденного статуса вместо флага. Пока этих гарантий нет,
отчитаться об удалении — значит соврать, а упасть с понятной причиной — нет.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import datetime, timedelta
from typing import NoReturn

from app.storage.retention import (
    AUDIT_LOG_DAYS,
    DELETION_SLA_HOURS,
    RESULTS_DAYS,
    SOURCE_DAYS,
    TECH_LOG_DAYS,
    retention_until,
)

__all__ = [
    "AUDIT_LOG_DAYS",
    "DEFAULT_RETENTION",
    "DEFAULT_RETENTION_KIND",
    "DELETION_SLA_HOURS",
    "RESULTS_DAYS",
    "SOURCE_DAYS",
    "TECH_LOG_DAYS",
    "purge_objects",
    "resolve_retention_until",
]

#: Род хранения, к которому приравнивается строка без уточнения. Не «побольше
#: на всякий случай», а самый долгий предметный срок: строка обязана пережить
#: любой объект, ключ которого в ней записан.
DEFAULT_RETENTION_KIND = "results"

#: Срок хранения строки по умолчанию. Величина не своя: она выведена из
#: `RESULTS_DAYS`, и правка там меняет ее здесь.
DEFAULT_RETENTION: timedelta = timedelta(days=RESULTS_DAYS)


def resolve_retention_until(
    deleted_at: datetime, *, kind: str = DEFAULT_RETENTION_KIND
) -> datetime:
    """Момент, после которого удаленную строку можно снести физически.

    Незнакомый род — ошибка `ValueError` из `app/storage/retention.py`, а не
    тихое умолчание: срок, взятый наугад, либо стирает оплаченный результат
    раньше разрешенного, либо хранит дольше обещанного. Оба исхода хуже
    падения на месте.
    """
    return retention_until(kind, deleted_at)


def purge_objects(storage_keys: Sequence[str]) -> NoReturn:
    """Физическое удаление объектов из хранилища. Не реализовано.

    Вызывать можно: падение с понятной причиной — это и есть честный ответ.
    Реализация появляется вместе с гарантиями дизайн-дока: выключенное
    версионирование объектов, удаление неактуальных версий, чистка кэша CDN,
    отзыв выданных ссылок и подтвержденный статус вместо флага.
    """
    raise NotImplementedError(
        "Физическое удаление объектов не реализовано: у хранилища нет гарантий, "
        "без которых удаление нельзя подтвердить (версионирование, кэш CDN, "
        f"отзыв ссылок). Запрошено ключей: {len(storage_keys)}. "
        "Пока их нет, статус удаления не может быть 'purged'."
    )
