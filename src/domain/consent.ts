/**
 * Версии текста согласия (B58).
 *
 * Задним числом это не чинится. Если не записать, какую именно формулировку
 * человек принял, восстановить её потом неоткуда: текст на экране меняется,
 * а запись «согласие получено» остаётся без предмета.
 *
 * До этого модуля было хуже, чем «без версии»: на экране показывалась одна
 * формулировка («Я вправе обработать этот материал…»), а в проект
 * записывалась другая («Материал используется для приватной репетиции…»).
 * Запись свидетельствовала о том, чего пользователь не читал.
 *
 * Правила работы с файлом:
 *
 * 1. Текст действующей версии **не редактируется**. Любая правка формулировки
 *    — новая версия с новым `id` и новой датой.
 * 2. Старые версии остаются в файле навсегда: по ним читаются старые записи.
 * 3. `fingerprint` считается от текста и проверяется тестом. Он существует
 *    ровно затем, чтобы правку текста нельзя было внести, не тронув версию.
 *
 * Формулировки — предмет разговора с юристом (`docs/LEGAL_BRIEF.md`),
 * не редактуры.
 */

export interface ConsentVersion {
  id: string;
  /** С какой даты формулировка действует. */
  effectiveFrom: string;
  /** Точный текст, который видит пользователь. */
  text: string;
  /** Контрольная сумма текста. Защищает от правки без смены версии. */
  fingerprint: number;
}

/** Устойчивая контрольная сумма строки. Не криптография: задача — заметить
 *  правку текста, а не защититься от подделки. */
export const fingerprintOf = (text: string): number => {
  let hash = 0;
  for (let index = 0; index < text.length; index += 1) {
    hash = (hash * 31 + text.charCodeAt(index)) | 0;
  }
  return hash;
};

const CONSENT_TEXT_1 =
  "Я вправе обработать этот материал для приватной репетиции, урока или внутренней подготовки.";

/** Все версии, от старых к новым. Удалять записи отсюда нельзя. */
export const consentVersions: ConsentVersion[] = [
  {
    id: "consent-2026-09-10",
    effectiveFrom: "2026-09-10",
    text: CONSENT_TEXT_1,
    fingerprint: fingerprintOf(CONSENT_TEXT_1),
  },
];

/** Версия, действующая сейчас. */
export const currentConsent = (): ConsentVersion => consentVersions[consentVersions.length - 1];

/** Текст по идентификатору версии: по нему читаются старые записи. */
export const consentTextById = (versionId: string): string | null =>
  consentVersions.find((version) => version.id === versionId)?.text ?? null;
