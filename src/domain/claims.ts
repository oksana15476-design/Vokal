/**
 * Реестр обещаний интерфейса (B11a).
 *
 * Здесь собрано то, что продукт заявляет пользователю о себе: чего он НЕ
 * обещает и что обязан раскрыть. До этого модуля обе половины жили
 * россыпью — запреты списком регулярных выражений внутри теста, раскрытия
 * нигде. Следствие: запрет можно было потерять при правке теста, а
 * раскрытие исчезало из вёрстки бесследно.
 *
 * Модуль не заменяет юриста. Это инвентаризация того, что уже сказано в
 * интерфейсе, чтобы список был предметом разговора с ним, а не
 * реконструировался по коду каждый раз. Вопросы к юристу — в
 * `docs/LEGAL_BRIEF.md`.
 */

export interface ForbiddenClaim {
  id: string;
  /** Что именно ищем в тексте интерфейса. */
  pattern: RegExp;
  /** Почему запрещено — не «нельзя», а чем это неправда сегодня. */
  because: string;
  /** Что должно появиться в продукте, чтобы запрет сняли. */
  allowedWhen: string;
}

